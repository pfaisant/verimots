let lang = 'fr'
let dict = 'ods'
let lastEnDict = 'wow24'
let esEdition = 'fise'

/** UI languages, in the order the language switch shows them. */
export const LANGS = ['fr', 'en', 'es', 'ca']

export const DICTS = [
  { id: 'ods', lang: 'fr' },
  { id: 'csw', lang: 'en' },
  { id: 'wow24', lang: 'en' },
  { id: 'rla', lang: 'es' },
  { id: 'disc', lang: 'ca' },
]

export function getLang() {
  return lang
}

export function getDict() {
  return dict
}

/** Spanish tile set: 'fise' (international, 100 tiles) or 'na' (103 tiles). */
export function getEsEdition() {
  return esEdition
}

export function setEsEdition(next) {
  esEdition = next === 'na' ? 'na' : 'fise'
  try {
    localStorage.setItem('verimots-es-edition', esEdition)
  } catch {
    /* ignore */
  }
  try {
    document.dispatchEvent(new CustomEvent('verimots-edition', { detail: esEdition }))
  } catch {
    /* ignore */
  }
  return esEdition
}

export function dictSpec(id) {
  const key = id === 'yawl' ? 'csw' : id
  return DICTS.find((item) => item.id === key) || DICTS[0]
}

export function defaultDictFor(nextLang) {
  if (nextLang === 'en') return 'wow24'
  if (nextLang === 'es') return 'rla'
  if (nextLang === 'ca') return 'disc'
  return 'ods'
}

export function dictLabel(id = getDict()) {
  return t(`dict_using_${dictSpec(id).id}`)
}

export function t(key, ...args) {
  const pack = STR[lang] || STR.fr
  const v = pack[key] ?? STR.fr[key] ?? key
  return typeof v === 'function' ? v(...args) : v
}

export function applyDom() {
  if (typeof document === 'undefined') return
  document.documentElement.lang = lang
  const title = document.querySelector('title')
  if (title) title.textContent = t('title')
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n')
    if (key) el.textContent = t(key)
  })
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder')
    if (key) el.setAttribute('placeholder', t(key))
  })
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria')
    if (key) el.setAttribute('aria-label', t(key))
  })
  for (const code of LANGS) {
    const btn = document.getElementById(`lang-${code}`)
    if (btn) btn.setAttribute('aria-pressed', lang === code ? 'true' : 'false')
  }
}

function persist() {
  if (lang === 'en') lastEnDict = dict
  try {
    localStorage.setItem('verimots-lang', lang)
    localStorage.setItem('verimots-dict', dict)
    if (lang === 'en') localStorage.setItem('verimots-dict-en', dict)
  } catch {
    /* ignore */
  }
}

function notify() {
  applyDom()
  try {
    document.dispatchEvent(new CustomEvent('verimots-lang', { detail: lang }))
    document.dispatchEvent(new CustomEvent('verimots-dict', { detail: dict }))
  } catch {
    /* ignore */
  }
}

function lastEnglishDict() {
  try {
    const saved = localStorage.getItem('verimots-dict-en') || lastEnDict
    return saved === 'csw' || saved === 'yawl' ? 'csw' : 'wow24'
  } catch {
    return lastEnDict === 'csw' || lastEnDict === 'yawl' ? 'csw' : 'wow24'
  }
}

export function setDict(id) {
  const spec = dictSpec(id)
  dict = spec.id
  lang = spec.lang
  persist()
  notify()
  return dict
}

export function setLang(next) {
  lang = LANGS.includes(next) ? next : 'fr'
  if (dictSpec(dict).lang !== lang) dict = lang === 'en' ? lastEnglishDict() : defaultDictFor(lang)
  persist()
  notify()
}

export function initLang() {
  let savedLang = ''
  let savedDict = ''
  try {
    savedLang = localStorage.getItem('verimots-lang') || ''
    savedDict = localStorage.getItem('verimots-dict') || ''
    esEdition = localStorage.getItem('verimots-es-edition') === 'na' ? 'na' : 'fise'
  } catch {
    savedLang = ''
    savedDict = ''
  }
  let urlLang = ''
  let urlDict = ''
  try {
    const query = new URLSearchParams(location.search)
    urlLang = query.get('lang') || ''
    urlDict = query.get('dict') || ''
  } catch {
    urlLang = ''
    urlDict = ''
  }
  if (LANGS.includes(urlLang)) savedLang = urlLang
  lang = LANGS.includes(savedLang) && savedLang !== 'fr' ? savedLang : 'fr'
  const spec = dictSpec(savedDict)
  dict = spec.lang === lang ? spec.id : lang === 'en' ? lastEnglishDict() : defaultDictFor(lang)
  if (urlDict) {
    const fromUrl = dictSpec(urlDict)
    dict = fromUrl.id
    lang = fromUrl.lang
  }
  if (lang === 'en') lastEnDict = dict
  persist()
  applyDom()
  return lang
}
